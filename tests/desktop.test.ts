import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const {allowsClipboard, allowsMicrophone}=require(resolve('desktop/permissions.cjs'));
const {sessionOrigin, desktopPort, serviceFailureMessage}=require(resolve('desktop/session-origin.cjs'));
test('Desktop permite copiar texto somente da origem local e continua negando leitura do clipboard',()=>{
 const origin='http://127.0.0.1:4318';assert.equal(allowsClipboard('clipboard-sanitized-write',origin+'/',origin+'/',origin),true);
 for(const [permission,request,main] of [['clipboard-read',origin,origin],['clipboard-sanitized-write','https://evil.example',origin],['clipboard-sanitized-write',origin,'https://evil.example'],['media',origin,origin],['clipboard-sanitized-write','file:///tmp/index.html',origin]])assert.equal(allowsClipboard(permission,request,main,origin),false);
});
test('Sessão do desktop adota a porta real e o microfone acompanha essa origem',()=>{
 assert.equal(desktopPort({}),4318);
 assert.equal(desktopPort({LOCALNEURON_TEST_PORT:'14318'}),14318);
 assert.throws(()=>desktopPort({LOCALNEURON_TEST_PORT:'abc'}),/LOCALNEURON_TEST_PORT inválida/);
 const same=sessionOrigin({url:'http://127.0.0.1:4318/#session=abc',port:4318},4318);
 assert.equal(same.origin,'http://127.0.0.1:4318');assert.equal(same.fallback,false);assert.equal(same.message,null);
 const moved=sessionOrigin({url:'http://127.0.0.1:4319/#session=abc',port:4319},4318);
 assert.equal(moved.origin,'http://127.0.0.1:4319');
 assert.equal(moved.message,'A porta 4318 está em uso por outro programa. O LocalNeuron abriu na porta 4319.');
 assert.throws(()=>sessionOrigin({url:'https://evil.example/#session=abc',port:4319},4318),/Sessão local inválida/);
 assert.throws(()=>sessionOrigin({url:'http://127.0.0.1:4320/#session=abc',port:4319},4318),/Sessão local inválida/);
 assert.equal(serviceFailureMessage('Error: listen EADDRINUSE\nA porta 4318 está em uso por outro programa.\n'),'A porta 4318 está em uso por outro programa.');
 assert.equal(serviceFailureMessage('COLMEIA_PORT inválida. Use um número de 1 a 65535.\n'),'COLMEIA_PORT inválida. Use um número de 1 a 65535.');
 assert.equal(serviceFailureMessage('LOCALNEURON_PORT inválida. Use um número de 1 a 65535.\n'),'LOCALNEURON_PORT inválida. Use um número de 1 a 65535.');
 assert.equal(serviceFailureMessage('stack cru'),'O serviço local encerrou: stack cru');
 const origin=moved.origin;
 assert.equal(allowsMicrophone('media',origin,origin,{mediaType:'audio'},origin),true);
 assert.equal(allowsMicrophone('media','http://127.0.0.1:4318',origin,{mediaType:'audio'},origin),false);
 assert.equal(allowsMicrophone('media',origin,'http://127.0.0.1:4318',{mediaType:'audio'},origin),false);
 const main=readFileSync(resolve('desktop/main.cjs'),'utf8');
 assert.match(main,/sessionOrigin\(localSession, preferred\)/);
 assert.match(main,/LOCALNEURON_PORT: String\(preferred\)/);
 assert.match(main,/registerFolderPicker\(\{ipcMain,dialog,getWindow:\(\)=>window,origin\}\)/);
 const calls=main.match(/allowsMicrophone\([\s\S]*?,origin\)/g)||[];
 assert.equal(calls.length,2);
});
